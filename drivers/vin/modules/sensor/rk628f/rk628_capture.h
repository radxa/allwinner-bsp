/* Shared with the host self-check: allow only progressive single-port modes. */
static inline unsigned int rk628_capture_fps(unsigned int width, unsigned int height,
					     unsigned int htotal, unsigned int vtotal,
					     unsigned long long pixelclock, unsigned int interlaced)
{
	unsigned int fps;
	unsigned long long nominal, delta;

	if (interlaced || htotal <= width || vtotal <= height ||
	    htotal > 8191 || vtotal > 8191 ||
	    pixelclock < 25000000 || pixelclock > 300000000)
		return 0;
	if (!((width == 1280 && height == 720) ||
	      (width == 1920 && height == 1080) ||
	      (width == 3840 && height == 2160)))
		return 0;
	for (fps = 30; fps <= 60; fps += 30) {
		if ((width == 1280 && fps != 60) || (width == 3840 && fps != 30))
			continue;
		nominal = (unsigned long long)htotal * vtotal * fps;
		delta = pixelclock > nominal ? pixelclock - nominal : nominal - pixelclock;
		/* Allow one percent for source-clock error and measurement jitter. */
		if (delta * 100 <= nominal)
			return fps;
	}
	return 0;
}

static inline unsigned int rk628_capture_bps(unsigned long long pixelclock)
{
	return pixelclock > 150000000 ? 1300000000U : 700000000U;
}

